#!/usr/bin/env bash
# Generate the benchmark workspace configs for every runner, so the same task
# definitions stay in lock-step across tsr / npm+bun+nub / just / go-task / make / deno.
#
# Scenarios (see run.sh):
#   startup  one task that spawns `true`            — per-invocation overhead
#   steps5   one task, 5 sequential commands        — in-task sequencing
#   graph5   one task with 5 trivial dependencies   — dependency-graph overhead
#   graph10  one task with 10 trivial dependencies  — graph overhead, scaled
#   topoN    N packages in a dependency chain        — topological fan-out (^task)
#
# The topo workspaces live in topo/<N>/ and are a different shape: a real
# multi-package workspace, generated for the three runners that order packages by
# dependency (tsr, pnpm, bun). See gen_topo below.
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
ws="$here/workspace"
mkdir -p "$ws"

STEPS=5
SMALL=5
LARGE=10
MAXS=$LARGE

# --- tsr: tasks.toml ---
{
  echo "# Generated by gen-workspace.sh — do not edit by hand."
  echo
  echo "[tasks.noop]"
  echo 'run = "true"'
  echo
  echo "[tasks.steps5]"
  printf 'run = "%s"\n' "$(yes true | head -n $STEPS | paste -sd' ' - | sed 's/ / \&\& /g')"
  for i in $(seq 1 $MAXS); do
    echo
    echo "[tasks.s$i]"
    echo 'run = "true"'
  done
  echo
  echo "[tasks.shell]"
  # Exercises tsr's mini-shell: $VAR expansion + && sequencing, no shell launched.
  echo 'run = "echo $HOME && echo ok"'
  echo
  echo "[tasks.builtins]"
  # Exercises tsr's in-process coreutils: mkdir, touch, cp, mv, rm
  echo 'run = "mkdir -p _bench_tmp && touch _bench_tmp/a.txt && cp _bench_tmp/a.txt _bench_tmp/b.txt && mv _bench_tmp/b.txt _bench_tmp/c.txt && rm -rf _bench_tmp"'
  echo
  echo "[tasks.globbing]"
  # Exercises tsr's in-process glob expansion
  echo 'run = "echo src/*.rs"'
  echo
  echo "[tasks.cli]"
  # Calls a locally-installed binary from node_modules/.bin (like vite/eslint).
  echo 'run = "localcli"'
  echo
  echo "[tasks.graph5]"
  echo "deps = [$(seq 1 $SMALL | sed 's/.*/"s&"/' | paste -sd, -)]"
  echo
  echo "[tasks.graph10]"
  echo "deps = [$(seq 1 $LARGE | sed 's/.*/"s&"/' | paste -sd, -)]"
} > "$ws/tasks.toml"

# --- npm / bun / nub: package.json (s1..sN and steps5; graphs are chained in run.sh) ---
{
  echo '{'
  echo '  "name": "tsr-bench-workspace",'
  echo '  "private": true,'
  echo '  "version": "0.0.0",'
  echo '  "scripts": {'
  echo '    "noop": "true",'
  echo '    "shell": "echo $HOME && echo ok",'
  echo '    "builtins": "mkdir -p _bench_tmp && touch _bench_tmp/a.txt && cp _bench_tmp/a.txt _bench_tmp/b.txt && mv _bench_tmp/b.txt _bench_tmp/c.txt && rm -rf _bench_tmp",'
  echo '    "globbing": "echo src/*.rs",'
  echo '    "cli": "localcli",'
  printf '    "steps5": "%s",\n' "$(yes true | head -n $STEPS | paste -sd' ' - | sed 's/ / \&\& /g')"
  for i in $(seq 1 $MAXS); do
    printf '    "s%s": "true"%s\n' "$i" "$([ "$i" -lt "$MAXS" ] && echo , )"
  done
  echo '  }'
  echo '}'
} > "$ws/package.json"

# --- deno: deno.json ---
{
  echo '{'
  echo '  "tasks": {'
  echo '    "noop": "true",'
  echo '    "shell": "echo $HOME && echo ok",'
  echo '    "builtins": "mkdir -p _bench_tmp && touch _bench_tmp/a.txt && cp _bench_tmp/a.txt _bench_tmp/b.txt && mv _bench_tmp/b.txt _bench_tmp/c.txt && rm -rf _bench_tmp",'
  echo '    "globbing": "echo src/*.rs",'
  echo '    "cli": "localcli",'
  printf '    "steps5": "%s",\n' "$(yes true | head -n $STEPS | paste -sd' ' - | sed 's/ / \&\& /g')"
  for i in $(seq 1 $MAXS); do
    printf '    "s%s": "true"%s\n' "$i" "$([ "$i" -lt "$MAXS" ] && echo , )"
  done
  echo '  }'
  echo '}'
} > "$ws/deno.json"


# --- just: justfile ---
{
  echo "# Generated by gen-workspace.sh"
  echo
  printf 'noop:\n    @true\n\n'
  printf 'shell:\n    @echo $HOME && echo ok\n\n'
  printf 'builtins:\n    @mkdir -p _bench_tmp && touch _bench_tmp/a.txt && cp _bench_tmp/a.txt _bench_tmp/b.txt && mv _bench_tmp/b.txt _bench_tmp/c.txt && rm -rf _bench_tmp\n\n'
  printf 'globbing:\n    @echo src/*.rs\n\n'
  printf 'steps5:\n'
  for _ in $(seq 1 $STEPS); do printf '    @true\n'; done
  printf '\n'
  for i in $(seq 1 $MAXS); do printf 's%s:\n    @true\n\n' "$i"; done
  printf 'graph5: %s\n\n' "$(seq 1 $SMALL | sed 's/.*/s&/' | paste -sd' ' -)"
  printf 'graph10: %s\n' "$(seq 1 $LARGE | sed 's/.*/s&/' | paste -sd' ' -)"
} > "$ws/justfile"

# --- go-task: Taskfile.yml ---
{
  echo "# Generated by gen-workspace.sh"
  echo 'version: "3"'
  echo
  echo "tasks:"
  echo "  noop:"
  echo "    silent: true"
  echo "    cmds: [true]"
  echo "  shell:"
  echo "    silent: true"
  echo '    cmds: ["echo $HOME && echo ok"]'
  echo "  builtins:"
  echo "    silent: true"
  echo '    cmds: ["mkdir -p _bench_tmp && touch _bench_tmp/a.txt && cp _bench_tmp/a.txt _bench_tmp/b.txt && mv _bench_tmp/b.txt _bench_tmp/c.txt && rm -rf _bench_tmp"]'
  echo "  globbing:"
  echo "    silent: true"
  echo '    cmds: ["echo src/*.rs"]'
  echo "  steps5:"
  echo "    silent: true"
  echo "    cmds: [$(yes true | head -n $STEPS | paste -sd, -)]"
  for i in $(seq 1 $MAXS); do
    echo "  s$i:"
    echo "    silent: true"
    echo "    cmds: [true]"
  done
  echo "  graph5:"
  echo "    silent: true"
  echo "    cmds:"
  for i in $(seq 1 $SMALL); do echo "      - task: s$i"; done
  echo "  graph10:"
  echo "    silent: true"
  echo "    cmds:"
  for i in $(seq 1 $LARGE); do echo "      - task: s$i"; done
} > "$ws/Taskfile.yml"

# --- make: Makefile (tabs required for recipes) ---
{
  echo "# Generated by gen-workspace.sh"
  echo ".PHONY: noop shell builtins globbing steps5 graph5 graph10 $(seq 1 $MAXS | sed 's/.*/s&/' | paste -sd' ' -)"
  echo
  printf 'noop:\n\t@true\n\n'
  # $$ escapes to a literal $ for the recipe shell.
  printf 'shell:\n\t@echo $$HOME && echo ok\n\n'
  printf 'builtins:\n\t@mkdir -p _bench_tmp && touch _bench_tmp/a.txt && cp _bench_tmp/a.txt _bench_tmp/b.txt && mv _bench_tmp/b.txt _bench_tmp/c.txt && rm -rf _bench_tmp\n\n'
  printf 'globbing:\n\t@echo src/*.rs\n\n'
  printf 'steps5:\n'
  for _ in $(seq 1 $STEPS); do printf '\t@true\n'; done
  printf '\n'
  for i in $(seq 1 $MAXS); do printf 's%s:\n\t@true\n\n' "$i"; done
  printf 'graph5: %s\n\n' "$(seq 1 $SMALL | sed 's/.*/s&/' | paste -sd' ' -)"
  printf 'graph10: %s\n' "$(seq 1 $LARGE | sed 's/.*/s&/' | paste -sd' ' -)"
} > "$ws/Makefile"

# --- mise: mise.toml ---
{
  echo "# Generated by gen-workspace.sh"
  echo "[tasks.noop]"
  echo 'run = "true"'
  echo "[tasks.shell]"
  echo 'run = "echo $HOME && echo ok"'
  echo "[tasks.builtins]"
  echo 'run = "mkdir -p _bench_tmp && touch _bench_tmp/a.txt && cp _bench_tmp/a.txt _bench_tmp/b.txt && mv _bench_tmp/b.txt _bench_tmp/c.txt && rm -rf _bench_tmp"'
  echo "[tasks.globbing]"
  echo 'run = "echo src/*.rs"'
  echo "[tasks.steps5]"
  echo "run = [$(yes '"true"' | head -n $STEPS | paste -sd, -)]"
  for i in $(seq 1 $MAXS); do
    echo "[tasks.s$i]"
    echo 'run = "true"'
  done
  echo "[tasks.graph5]"
  echo "depends = [$(seq 1 $SMALL | sed 's/.*/"s&"/' | paste -sd, -)]"
  echo "[tasks.graph10]"
  echo "depends = [$(seq 1 $LARGE | sed 's/.*/"s&"/' | paste -sd, -)]"
} > "$ws/mise.toml"

# --- a locally-installed Node CLI in node_modules/.bin ---
# Stands in for vite/eslint (Node programs): the `cli`/`localbin` scenario measures
# tsr vs npm vs bun resolving and launching a project-local binary. Not committed
# (node_modules is gitignored); regenerated here.
mkdir -p "$ws/node_modules/.bin"
cat > "$ws/node_modules/.bin/localcli" <<'EOF'
#!/usr/bin/env node
// Minimal stand-in for a real local CLI (eslint/vite are Node programs too).
process.exit(0);
EOF
chmod +x "$ws/node_modules/.bin/localcli"

# --- topo/<N>: multi-package workspaces for the topological fan-out scenarios ---
#
# Package pK depends on pK+1, so the correct build order is the exact REVERSE of
# alphabetical order. That matters: a runner that merely walks packages in name
# order produces the wrong order here, so the scenario measures *ordering* rather
# than iteration. (Verified: tsr, pnpm and bun all reverse it; `npm --workspaces`
# does not, which is why npm sits this one out — see run.sh.)
#
# Each package's `build` is `true`, so what is timed is the runner resolving the
# package graph and dispatching, not the work.
gen_topo() {
  local n="$1" dir="$here/topo/$n" i name pkgdir deps next
  rm -rf "$dir"
  mkdir -p "$dir/packages"
  for ((i = 1; i <= n; i++)); do
    name=$(printf 'p%03d' "$i")
    pkgdir="$dir/packages/$name"
    mkdir -p "$pkgdir"
    deps=""
    if ((i < n)); then
      next=$(printf 'p%03d' $((i + 1)))
      deps="\"$next\": \"workspace:*\""
    fi
    printf '{"name":"%s","version":"1.0.0","scripts":{"build":"true"},"dependencies":{%s}}\n' \
      "$name" "$deps" > "$pkgdir/package.json"
  done

  # npm/bun workspace root, and pnpm's separate workspace file.
  printf '{"name":"tsr-bench-topo%s","private":true,"version":"1.0.0","workspaces":["packages/*"]}\n' \
    "$n" > "$dir/package.json"
  printf 'packages:\n  - "packages/*"\n' > "$dir/pnpm-workspace.yaml"

  {
    echo "# Generated by gen-workspace.sh — do not edit by hand."
    echo
    echo "[workspace]"
    echo 'members = ["packages/*"]'
    echo
    echo "[tasks.build]"
    echo 'packages = ["packages/*"]'
    echo 'deps = ["^build"]'
    echo 'run = "true"'
  } > "$dir/tasks.toml"
}

TOPO_SIZES=(10 50 200)
for n in "${TOPO_SIZES[@]}"; do gen_topo "$n"; done

echo "generated $ws/{tasks.toml,package.json,deno.json,justfile,Taskfile.yml,Makefile,mise.toml} + node_modules/.bin/localcli"
echo "generated $here/topo/{$(IFS=,; echo "${TOPO_SIZES[*]}")}/ (tsr + pnpm + bun multi-package workspaces)"
